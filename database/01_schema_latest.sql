CREATE INDEX idx_chat_message_room_no
    ON chat_message(room_no);

CREATE INDEX idx_chat_message_created_date
    ON chat_message(created_date);

CREATE INDEX idx_visit_log_member_no
    ON visit_log(member_no);

CREATE INDEX idx_visit_log_created_date
    ON visit_log(created_date);

CREATE INDEX idx_visit_log_request_uri
    ON visit_log(request_uri);


