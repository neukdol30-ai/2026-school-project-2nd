-- 기존 DB를 유지하면서 답변 완료 시각 기능만 추가할 때 이 파일을 실행
-- BOARD 테이블이 먼저 존재해야 함
-- 한 번만 실행. 두 번 실행하면 이미 존재하는 객체 오류 발생
-- ════════════════════════════════════════════════════════════


-- ════════════════════════════════════════════════════════════
-- [1] BOARD에 답변 완료 시각 컬럼 추가
-- 문의글에 마지막으로 답변이 등록된 시각을 저장
-- NOT NULL을 붙이지 않는 이유: 기존 게시글에 넣을 값이 없어 ALTER 자체가 실패함
-- 따라서 기존 게시글의 answered_date는 NULL로 남음
-- ════════════════════════════════════════════════════════════
ALTER TABLE board
ADD answered_date TIMESTAMP;


-- ════════════════════════════════════════════════════════════
-- [2] 비회원 문의글 자동 삭제 조회용 인덱스 추가
-- 필수는 아니지만 삭제 대상 조회 속도가 빨라짐
--
-- 컬럼 순서는 삭제 스케줄러의 조회 조건 순서와 맞춰져 있음
--   category = 'QUESTION'  ->  answer_status = 'ANSWERED'
--   ->  answered_date 기간 비교  ->  guest_author_no 로 비회원 글만 선별
--
-- 기존 idx_board_category_status(category, answer_status)와
-- 앞 두 컬럼이 같지만, 컬럼 목록 전체가 다르므로 ORA-01408은 발생하지 않음
-- ════════════════════════════════════════════════════════════
CREATE INDEX idx_board_guest_cleanup
    ON board (category, answer_status, answered_date, guest_author_no);
