-- ════════════════════════════════════════════════════════════
-- secondpro 프로젝트 테이블 생성 SQL
-- 기준: Oracle / DBeaver / MyBatis · DB 계정: secondpro
-- 실행 순서: member → social_account → chat_room → chat_message
--            → board → board_file → board_comment
-- ════════════════════════════════════════════════════════════


-- ════════════════════════════════════════════════════════════
-- [1] 회원(MEMBER) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE member (
    no               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    member_id        VARCHAR2(100 CHAR),
    password         VARCHAR2(255 CHAR),
    name             VARCHAR2(50 CHAR),
    nickname         VARCHAR2(50 CHAR) NOT NULL,
    email            VARCHAR2(100 CHAR),
    phone            VARCHAR2(20 CHAR),
    birth_date       DATE,
    gender           VARCHAR2(10 CHAR),
    postcode         VARCHAR2(10 CHAR),
    address          VARCHAR2(255 CHAR),
    detail_address   VARCHAR2(255 CHAR),
    role             VARCHAR2(20 CHAR) DEFAULT 'USER' NOT NULL,
    profile_image    VARCHAR2(500 CHAR),
    last_login_date  TIMESTAMP,
    agree_terms_yn   CHAR(1)   DEFAULT 'N'          NOT NULL,
    agree_privacy_yn CHAR(1)   DEFAULT 'N'          NOT NULL,
    regdate          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_member PRIMARY KEY (no),
    CONSTRAINT uk_member_member_id UNIQUE (member_id),
    CONSTRAINT uk_member_email UNIQUE (email),
    CONSTRAINT ck_member_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_member_agree_terms CHECK (agree_terms_yn IN ('Y', 'N')),
    CONSTRAINT ck_member_agree_privacy CHECK (agree_privacy_yn IN ('Y', 'N'))
);


-- ════════════════════════════════════════════════════════════
-- [2] 소셜 계정(SOCIAL_ACCOUNT) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE social_account (
    no           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    member_no    NUMBER                         NOT NULL,
    provider     VARCHAR2(30 CHAR) NOT NULL,
    provider_id  VARCHAR2(255 CHAR) NOT NULL,
    created_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_social_account PRIMARY KEY (no),
    CONSTRAINT uk_social_provider UNIQUE (provider, provider_id),
    CONSTRAINT fk_social_member FOREIGN KEY (member_no)
        REFERENCES member (no) ON DELETE CASCADE
);


-- ════════════════════════════════════════════════════════════
-- [3] 1:1 문의 - 채팅방(CHAT_ROOM) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE chat_room (
    room_no           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_no           NUMBER,
    admin_no          NUMBER,
    status            VARCHAR2(20 CHAR) DEFAULT 'OPEN' NOT NULL,
    last_message      VARCHAR2(1000 CHAR),
    last_message_date TIMESTAMP,
    created_date      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    closed_date       TIMESTAMP,

    CONSTRAINT pk_chat_room PRIMARY KEY (room_no),
    CONSTRAINT ck_chat_room_status CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT fk_chat_room_user FOREIGN KEY (user_no)
        REFERENCES member (no) ON DELETE SET NULL,
    CONSTRAINT fk_chat_room_admin FOREIGN KEY (admin_no)
        REFERENCES member (no) ON DELETE SET NULL
);

-- chat_room 테이블 문의 카테고리 컬럼 추가
ALTER TABLE chat_room
    ADD category VARCHAR2(30 CHAR) DEFAULT 'ETC' NOT NULL;

-- category 컬럼에는 정해진 값만 들어가게 제한
ALTER TABLE chat_room
    ADD CONSTRAINT ck_chat_room_category
        CHECK (
            category IN (
                         'MAIL',
                         'MAP',
                         'STOCK',
                         'NEWS',
                         'WEATHER',
                         'CALENDAR',
                         'ETC'
                )
            );

-- 카테고리별 문의 목록 조회가 많아질 경우를 대비한 인덱스
CREATE INDEX idx_chat_room_category
    ON chat_room (category);

-- ════════════════════════════════════════════════════════════
-- [4] 1:1 문의 - 채팅 메시지(CHAT_MESSAGE) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE chat_message (
    message_no      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    room_no         NUMBER                         NOT NULL,
    sender_no       NUMBER,
    message_content VARCHAR2(2000 CHAR) NOT NULL,
    read_yn         CHAR(1)   DEFAULT 'N'          NOT NULL,
    created_date    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_chat_message PRIMARY KEY (message_no),
    CONSTRAINT ck_chat_message_read CHECK (read_yn IN ('Y', 'N')),
    CONSTRAINT fk_chat_message_room FOREIGN KEY (room_no)
        REFERENCES chat_room (room_no) ON DELETE CASCADE,
    CONSTRAINT fk_chat_message_sender FOREIGN KEY (sender_no)
        REFERENCES member (no) ON DELETE SET NULL
);


-- ════════════════════════════════════════════════════════════
-- [5] 인덱스 (member / social / chat 계열)
-- ════════════════════════════════════════════════════════════
CREATE INDEX idx_social_member_no
    ON social_account (member_no);

CREATE INDEX idx_chat_room_user_no
    ON chat_room (user_no);

CREATE INDEX idx_chat_room_admin_no
    ON chat_room (admin_no);

CREATE INDEX idx_chat_message_room_no
    ON chat_message (room_no);

CREATE INDEX idx_chat_message_created_date
    ON chat_message (created_date);


-- ════════════════════════════════════════════════════════════
-- [6] 게시판(BOARD) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE board (
    no            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    writer_no     NUMBER,
    category      VARCHAR2(20 CHAR) DEFAULT 'NOTICE' NOT NULL,
    title         VARCHAR2(200 CHAR) NOT NULL,
    content       CLOB                           NOT NULL,
    view_count    NUMBER    DEFAULT 0            NOT NULL,
    created_date  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    modified_date TIMESTAMP,

    CONSTRAINT pk_board PRIMARY KEY (no),
    CONSTRAINT ck_board_category CHECK (category IN ('NOTICE', 'FAQ', 'FREE')),
    CONSTRAINT fk_board_writer FOREIGN KEY (writer_no)
        REFERENCES member (no) ON DELETE SET NULL
);


-- ════════════════════════════════════════════════════════════
-- [7] 게시판 첨부파일(BOARD_FILE) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE board_file (
    no           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    board_no     NUMBER                         NOT NULL,
    origin_name  VARCHAR2(255 CHAR) NOT NULL,
    stored_name  VARCHAR2(255 CHAR) NOT NULL,
    file_path    VARCHAR2(500 CHAR) NOT NULL,
    file_size    NUMBER                         NOT NULL,
    created_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_board_file PRIMARY KEY (no),
    CONSTRAINT fk_board_file_board FOREIGN KEY (board_no)
        REFERENCES board (no) ON DELETE CASCADE
);


-- ════════════════════════════════════════════════════════════
-- [8] 게시판 댓글(BOARD_COMMENT) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE board_comment (
    no            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    board_no      NUMBER                         NOT NULL,
    writer_no     NUMBER,
    content       VARCHAR2(1000 CHAR) NOT NULL,
    created_date  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    modified_date TIMESTAMP,

    CONSTRAINT pk_board_comment PRIMARY KEY (no),
    CONSTRAINT fk_board_comment_board FOREIGN KEY (board_no)
        REFERENCES board (no) ON DELETE CASCADE,
    CONSTRAINT fk_board_comment_writer FOREIGN KEY (writer_no)
        REFERENCES member (no) ON DELETE SET NULL
);


-- ════════════════════════════════════════════════════════════
-- [9] 인덱스 (board 계열)
-- ════════════════════════════════════════════════════════════
CREATE INDEX idx_board_writer_no
    ON board (writer_no);

CREATE INDEX idx_board_created_date
    ON board (created_date);

CREATE INDEX idx_board_category
    ON board (category);

CREATE INDEX idx_board_file_board_no
    ON board_file (board_no);

CREATE INDEX idx_board_comment_board_no
    ON board_comment (board_no);

CREATE INDEX idx_board_comment_writer_no
    ON board_comment (writer_no);