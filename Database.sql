-- ════════════════════════════════════════════════════════════
-- [쿠키/방문 기록] 방문 로그(VISIT_LOG) 테이블
-- ════════════════════════════════════════════════════════════
-- 사용자가 분석 쿠키를 허용한 경우에만 VisitLogInterceptor가 저장합니다.

CREATE TABLE visit_log (
   no             NUMBER GENERATED BY DEFAULT AS IDENTITY,
   member_no      NUMBER,
   session_id     VARCHAR2(100 CHAR),
   request_uri    VARCHAR2(500 CHAR),
   query_string   VARCHAR2(1000 CHAR),
   request_method VARCHAR2(20 CHAR),
   user_agent     VARCHAR2(1000 CHAR),
   ip_address     VARCHAR2(100 CHAR),
   referer         VARCHAR2(1000 CHAR),
   created_date   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

   CONSTRAINT pk_visit_log PRIMARY KEY (no),
   CONSTRAINT fk_visit_log_member FOREIGN KEY (member_no)
       REFERENCES member (no) ON DELETE SET NULL
);

CREATE INDEX idx_visit_log_member_no
    ON visit_log (member_no);

CREATE INDEX idx_visit_log_created_date
    ON visit_log (created_date);

CREATE INDEX idx_visit_log_request_uri
    ON visit_log (request_uri);

-- ════════════════════════════════════════════════════════════
-- [6] 게시판(BOARD) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE board (
    no            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    writer_no     NUMBER,
    category      VARCHAR2(20 CHAR) DEFAULT 'NOTICE' NOT NULL,
    title         VARCHAR2(200 CHAR) NOT NULL,
    content       CLOB                           NOT NULL,
    view_count    NUMBER    DEFAULT 0            NOT NULL,
    created_date  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    modified_date TIMESTAMP,

    CONSTRAINT pk_board PRIMARY KEY (no),
    CONSTRAINT ck_board_category CHECK (category IN ('NOTICE', 'FAQ', 'FREE')),
    CONSTRAINT fk_board_writer FOREIGN KEY (writer_no)
        REFERENCES member (no) ON DELETE SET NULL
);


-- ════════════════════════════════════════════════════════════
-- [7] 게시판 첨부파일(BOARD_FILE) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE board_file (
    no           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    board_no     NUMBER                         NOT NULL,
    origin_name  VARCHAR2(255 CHAR) NOT NULL,
    stored_name  VARCHAR2(255 CHAR) NOT NULL,
    file_path    VARCHAR2(500 CHAR) NOT NULL,
    file_size    NUMBER                         NOT NULL,
    created_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_board_file PRIMARY KEY (no),
    CONSTRAINT fk_board_file_board FOREIGN KEY (board_no)
        REFERENCES board (no) ON DELETE CASCADE
);


-- ════════════════════════════════════════════════════════════
-- [8] 게시판 댓글(BOARD_COMMENT) 테이블
-- ════════════════════════════════════════════════════════════
CREATE TABLE board_comment (
    no            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    board_no      NUMBER                         NOT NULL,
    writer_no     NUMBER,
    content       VARCHAR2(1000 CHAR) NOT NULL,
    created_date  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    modified_date TIMESTAMP,

    CONSTRAINT pk_board_comment PRIMARY KEY (no),
    CONSTRAINT fk_board_comment_board FOREIGN KEY (board_no)
        REFERENCES board (no) ON DELETE CASCADE,
    CONSTRAINT fk_board_comment_writer FOREIGN KEY (writer_no)
        REFERENCES member (no) ON DELETE SET NULL
);


